@pytest.mark.whisper
def test_faster_whisper_can_decode_audio(tmp_path: Path) -> None:
    """Catches faster-whisper / PyAV incompatibilities without downloading a model."""
    audio = pytest.importorskip("faster_whisper.audio")
    wav_path = tmp_path / "tone.wav"
    with wave.open(str(wav_path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(16000)
        w.writeframes(b"\x00\x10" * 16000)  # 1 s of a constant signal
    samples = audio.decode_audio(str(wav_path))
    assert samples.shape == (16000,)


@pytest.mark.whisper
@pytest.mark.skipif(os.environ.get("AMN_RUN_WHISPER") != "1", reason="set AMN_RUN_WHISPER=1 to run")
@pytest.mark.skipif(shutil.which("espeak-ng") is None, reason="needs espeak-ng to synthesise speech")
def test_real_whisper_transcribes_synthesised_speech(tmp_path: Path) -> None:
    """End-to-end with the real tiny.en model on speech generated by espeak-ng."""
    wav = tmp_path / "speech.wav"
    subprocess.run(  # noqa: S603
        ["espeak-ng", "-s", "140", "-w", str(wav), "Sam will send the budget report by Friday."],  # noqa: S607
        check=True,
    )
    result = FasterWhisperTranscriber("tiny.en", device="cpu", compute_type="int8").transcribe(wav)
    text = result.text.lower()
    assert "report" in text
    assert "friday" in text
    assert result.duration_s is not None
    assert result.duration_s > 1
